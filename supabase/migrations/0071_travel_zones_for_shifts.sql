-- 0071: אזור הנסיעה הוא נתון של משמרת, לא רק של תמחור
--
-- ‏0020 כבר קבעה ש-`app.task_travel_hours` הוא מקור אחד לזמן הנסיעה, ושהוא
-- מזין שני צרכנים: את נוסחת התמחור ואת גזירת המשמרת. הצד השני של אותה
-- החלטה מעולם לא נעשה — הנתון נשאר גלוי רק דרך מפתחות התמחור, בטבלה ששמה
-- `pricing_zones`, במסך שיושב בתוך לשונית "תמחור". התוצאה היא שמי שמתכנן
-- משמרות אינו יכול לראות את המספר שקובע כמה זמן העובד שלו בדרך.
--
-- ולזמן הזה יש משמעות ישירה במשמרת, בלי קשר לכסף: `app.planned_shifts`
-- (0023:117) מוסיפה אותו לסיום המשמרת — הנסיעה חזרה למחסן — ומי שיוצא מהמחסן
-- מתחיל את המשמרת שם. לקוח ב-`pricing_mode='manual'` אינו מתומחר בכלל
-- מהמחשבון, והמספר הזה עדיין מאריך לו את המשמרת ואת השכר.
--
-- הקובץ מרחיב את פוליסת הקריאה בלבד: `attendance.manage_warehouses` — המפתח
-- של מי שמגדיר את המחסנים שמהם יוצאים — נכנס ל-pz_select.
--
-- הכתיבה נשארת בידי `pricing.manage_rules`, וזו החלטה ולא השמטה: הטריגר
-- `pricing_zones_recalc` (0017:841) מחשב מחדש את כל המחירים העתידיים של
-- הלקוח בכל שינוי באזור. הרחבת הכתיבה הייתה נותנת למי שמנהל מחסנים להזיז
-- חשבוניות, וזה מפתח אחר לגמרי. מי שאמור גם לערוך מקבל את שני המפתחות.
--
-- מה שכן נחשף לקורא החדש הוא `surcharge` — עמודת כסף שיושבת על אותה שורה.
-- מיסוך שלה היה דורש view נפרד, והטבלה עצמה נשארת קריאה דרך ה-API ממילא,
-- ולכן החשיפה מוצהרת כאן ולא מתוקנת בדלת אחורית. המסך מסתיר את העמודה ממי
-- שאין לו `pricing.view`, כדי שלא תיקרא כהזמנה לערוך אותה.

drop policy if exists pz_select on pricing_zones;
create policy pz_select on pricing_zones for select to authenticated using (
  (select app.is_admin())
  or (deleted_at is null
      and (select app.user_kind()) = 'staff'
      and ((select app.has('pricing.manage_rules'))
           or (select app.has('pricing.view'))
           or (select app.has('attendance.manage_warehouses')))));

comment on table pricing_zones is
  'אזורי נסיעה: הגאומטריה שממנה נגזר זמן הנסיעה של משימה. הזמן מזין את '
  'נוסחת התמחור וגם את גזירת המשמרת (app.planned_shifts), ולכן הוא רלוונטי '
  'גם ללקוח בתמחור ידני.';

comment on column pricing_zones.travel_hours is
  'זמן נסיעה בכיוון אחד, בשעות. המשמרת מוסיפה אותו פעם אחת (החזרה למחסן '
  'מהמשימה האחרונה), ונוסחת התמחור מכפילה אותו בשתיים (הלוך-חזור).';
