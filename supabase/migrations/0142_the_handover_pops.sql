-- 0142: ההתראה על המעבר קופצת גם למכשיר
--
-- הדיווח: **"משימה שהיתה על וייפר והועברה לארקו, תקפיץ התראה למנהל מערכת."**
-- ההתראה **נשלחת** מאז 0136 — שורות הפעמון קיימות, שני מנהלי המערכת מקבלים
-- את שני הכיוונים — אבל היא אינה קופצת: ‏0136 רשמה את הסוג עם
-- `default_mode_push = 'opt_in'`, ולפי הסולם של 0086 ‏`opt_in` ⇒ **לא נשלח**.
--
-- ‏`opt_in` ו-`opt_out` נשארו בקטלוג כי הם ברירות המחדל שכבר שמורות בטבלת
-- המדיניות (0086), ולא כדי שמישהו יבחר ביניהם בטעות. ערוץ ה-push דלוק
-- במערכת וכל שאר הסוגים הם `opt_out` — הסוג הזה היה היחיד שנשאר בחוץ.
--
-- ‏`register_notification_type` הוא upsert על המפתח, ולכן זו קריאה חוזרת
-- זהה לזו של 0136 בשינוי ערך אחד. המדיניות שמנהל כבר קבע במסך אינה נדרסת:
-- היא יושבת ב-`notification_policies`, שכבה שקודמת לקטלוג בסולם.

select app.register_notification_type('task_performed_by_changed', 'המשימה עברה בין ארקו לוייפר',
  'מי מבצע את המשימה השתנה — לשני הכיוונים', 'משימות',
  array['admin'], 'task', 'forced', 'opt_out', 'opt_out', 22);
