-- 0157: אירוע אינו משוכפל
--
-- ‏"שכפול" נולד ב-0006 כקיצור דרך: אירוע חוזר אצל אותו לקוח, באותו מיקום,
-- עם אותן משימות — ולחיצה אחת במקום למלא את האשף מחדש. בשטח הוא הפך למקור
-- קבוע של אירועי-רפאים: העותק נולד בלי מספר אירוע, עם התאריך של המקור,
-- ובסטטוס ברירת המחדל — ולכן הוא נראה בלוח השנה כאירוע אמיתי לכל דבר עוד
-- לפני שמישהו נגע בו, וכל מי שראה אותו לא יכול היה לדעת אם זו טיוטה או
-- כפילות. הבקשה מהשטח היא להוריד את האפשרות, ולא לתקן אותה.
--
-- **הפונקציה יורדת, ולא רק הכפתור.** ‏`duplicate_event` הוא RPC שנחשף ב-
-- ‏PostgREST לכל משתמש מאומת שמחזיק את המפתח; הסרת הכפתור מהמסך הייתה
-- משאירה את הדלת פתוחה לכל קורא שיודע את שמה. ‏`drop function` הוא מה שסוגר
-- אותה, ו-`if exists` כדי שהמיגרציה תעבור גם על סביבה שכבר ניקתה אותה.
--
-- **המפתח יורד מהמרשם הפעיל ואינו נמחק.** אותו דפוס של 0129 (‏`events.
-- activity_note_view`) ושל סוגי ההתראה שהוצאו משימוש ב-0110: שורות ה-
-- ‏`role_permissions` שנכתבו עליו הן תיעוד של הכרעות שנעשו, ומחיקת המפתח
-- הייתה מוחקת אותן בקסקייד. הוא פשוט חדל להישאל — מסך ההרשאות אינו מציג
-- מפתח לא פעיל, ואין עוד קוד שקורא לו.
--
-- **מה שכבר שוכפל נשאר.** האירועים שנוצרו בדרך הזאת הם אירועים ככל אירוע
-- אחר, ואין כאן מה לנקות — זו הסרה של פעולה, לא של נתונים.

drop function if exists duplicate_event(uuid, date);

update permission_registry set is_active = false
 where key = 'events.duplicate';
