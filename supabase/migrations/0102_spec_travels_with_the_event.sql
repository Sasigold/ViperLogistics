-- 0102: המפרט נוסע עם האירוע — צפייה בו פתוחה לכל מי שרואה אותו
--
-- הבקשה במשפט אחד: "תאפשר צפייה במפרט לכל אחד". מי שנוסע לאירוע — העובד,
-- הנהג, ראש הצוות, עובד הקבלן ומנהלו, וגם איש הקשר אצל הלקוח — הוא בדיוק מי
-- שצריך לקרוא את המסמך שהלקוח שלח, והוא היחיד שלא ראה אותו. שתי שכבות נפרדות
-- עצרו אותו, ושתיהן נפתחות כאן:
--
--   1. **סוג המשתמש.** ‏0077 רשמה את `events.specs_view` כמפתח של אנשי צוות
--      בלבד — "מפרט אינו נגלה למשתמש פורטל" — ופוליסת ה-select אוכפת את זה
--      בשורה משלה: `user_kind() = 'staff'`. לקוח או קבלן שפתחו את האירוע קיבלו
--      רשימה ריקה, שנראית כמו "אין מפרט" ולא כמו "אין לך הרשאה".
--   2. **תפקידי השטח.** ‏0079 §2א ו-0080 פתחו לעובד, לנהג ולראש הצוות את
--      `events.view` וכתבו מחדש את *כל* שאר מודול האירועים כדחייה מפורשת,
--      בכתיבה גורפת (`cross join permission_registry`) ולא מפתח-מפתח. המפרט
--      נלכד בה יחד עם הייצוא והעריכה, תחת הנימוק "לראות את האירוע אינו לראות
--      את המסמך שהלקוח שלח". זו ההכרעה שמתהפכת כאן: המסמך אינו סוד פנימי —
--      הוא מה שצריך לבצע.
--
-- ההכרעה החדשה, בשורה אחת: **צפייה במפרט היא חלק מצפייה באירוע.** מי שהאירוע
-- נפתח לו — על כל היקפי השורות שב-`events_select`, ובלי קשר לסוג המשתמש —
-- רואה גם את המפרט שלו. מה ש*אינו* משתנה: העלאה והסרה נשארות אצל מי שמנהל את
-- האירוע, והן הסיבה שהמפתח `events.specs_view` נשאר קיים ולא נמחק — אפשר עדיין
-- לשלול אותו מאדם או מתפקיד, וזו רק חדלה להיות ברירת המחדל.

-- ===== 1. המפתח: פתוח כברירת מחדל, לכל סוגי המשתמש ========================
--
-- שני שינויים ברישום, ושניהם נדרשים:
--
--   * `default_allowed = true` — התשובה שנמצאת בשכבה האחרונה של `app.has`,
--     אחרי המענק האישי, אחרי התפקיד ואחרי ברירת המחדל של סוג המשתמש. כלומר:
--     פתוח לכולם, וכל אחת מהשכבות שמעליה עדיין יכולה לסגור.
--   * `applies_to` על שלושת סוגי המשתמש. ‏`app.has` אינו מסתכל עליו (0026),
--     אבל מטריצת ההרשאות כן: בלעדיו המפתח פשוט לא היה מופיע כשמגדירים תפקיד
--     של לקוח או של קבלן, ואי אפשר היה לשלול מהם את מה שזה עתה נפתח.
--
-- ‏`implied_by` יורד ל-null. ההיסק מ-`events.view` היה הדרך שבה מי שרואה אירוע
-- קיבל את המפרט, ומרגע שברירת המחדל פתוחה הוא מסלול שני לאותה תשובה — והמסלול
-- הזה מפסיק בשכבה הראשונה שיש לה דעה (0042), ולכן דחייה של `events.view`
-- הייתה גוררת איתה גם את המפרט בלי שאיש ביקש זאת.
select app.register_permission('events.specs_view', 'events', 'צפייה במפרט האירוע',
  'המפרט הפעיל, היסטוריית הגרסאות והשוואה ביניהן. פתוח לכל מי שרואה את האירוע',
  'field', true, false,
  array['staff', 'customer_user', 'contractor_user']::user_kind[], null, 210);

-- ו-`update` ישיר על ברירת המחדל עצמה, מאותה סיבה שכתובה ב-0072 §1: ה-
-- `on conflict do update` של `register_permission` מעדכן הכול חוץ מ-
-- `default_allowed`, בכוונה — כדי שרישום חוזר לא ישנה מדיניות. כאן המדיניות
-- היא בדיוק מה שמשתנה, ולכן היא נכתבת במפורש.
update permission_registry set default_allowed = true where key = 'events.specs_view';

-- ===== 2. שורות הדחייה של 0079/0080 יורדות ================================
--
-- בלעדיהן "לכל אחד" היה מדלג בדיוק על הקהל שבשבילו הבקשה נכתבה: שלושת תפקידי
-- השטח מחזיקים שורת `role_permissions` מפורשת עם allowed=false על המפתח הזה,
-- והיא גוברת על ברירת המחדל שנקבעה בסעיף 1.
--
-- מחיקה ולא היפוך ל-true: השורות נכתבו בכתיבה גורפת על מודול שלם ולא כהכרעה
-- על המפרט, ושורה שנמחקה מחזירה את התפקיד להישען על המרשם — כך שאם ברירת
-- המחדל תשתנה שוב, אין שורה ישנה שנלחמת בה.
--
-- מענק אישי (`user_permission_grants`) אינו נוגע כאן במכוון: הוא החלטה שמישהו
-- קיבל על אדם מסוים, ולא תוצר לוואי של cross join.
delete from role_permissions where permission_key = 'events.specs_view' and not allowed;

-- ===== 3. וניהול המפרט נשאר של הצוות ======================================
--
-- ‏`events.specs_manage` נגזר מ-`events.edit`, ו-`events.edit` פתוח למשתמש
-- לקוח בברירת המחדל של סוג המשתמש (0004, שהועברה ל-0011). כלומר מנהל אצל לקוח
-- החזיק את מפתח הניהול כל הזמן — פוליסת ה-INSERT על `event_specs` שואלת רק
-- אותו, בלי שאלה על סוג המשתמש — והדבר היחיד שעצר אותו היה
-- `app.may_touch_event_spec`, שחוסמת קובץ בדלי אך אינה נשאלת כלל על שורת
-- **קישור**. התוצאה הייתה שקטה: הוא יכול היה להוסיף גרסת קישור, ואיש — גם לא
-- הוא עצמו — לא ראה אותה, כי פוליסת ה-select הייתה סגורה.
--
-- סעיף 4 פותח את ה-select, ולכן הנתיב הזה חדל להיות בלתי נראה. ההכרעה של 0077
-- — "מפרט הוא מסמך פנימי, והעלאתו היא של מי שמנהל את האירוע" — נשארת בעינה,
-- והיא נאמרת כאן בשכבה שמתאימה לה: ברירת מחדל לסוג המשתמש, שמדברת *אחרי*
-- המענק האישי ואחרי התפקיד (0042). מי שירצה לתת ללקוח מסוים להעלות מפרט
-- בעצמו — יעניק לו את המפתח, וההענקה תגבר.
insert into kind_permission_defaults (user_kind, permission_key, allowed) values
  ('customer_user',   'events.specs_manage', false),
  ('contractor_user', 'events.specs_manage', false)
on conflict (user_kind, permission_key) do update set allowed = excluded.allowed;

-- ===== 4. פוליסת ה-select: המפתח והאירוע, ותו לא ==========================
--
-- זרוע ה-staff יורדת. מה שנשאר הוא בדיוק שתי השאלות שההכרעה מנסחת: האם הקורא
-- מחזיק את המפתח, והאם האירוע נפתח לו. ה-exists על `events` הוא מה שמחיל את
-- כל היקפי הראייה (0013, 0082, 0098) בלי לשכפל אף פרדיקט לכאן — ולכן עובד
-- שרואה רק את האירוע ששובץ אליו רואה רק את המפרט שלו.
--
-- עטיפת (select …) נשמרת כדי שהתנאי יישאר InitPlan ולא ירוץ פר-שורה (0028).
-- הזרוע הראשונה — גרסאות מוסרות לאדמין בלבד — לא נגעה מעולם בסוג המשתמש.
drop policy if exists event_specs_select on event_specs;
create policy event_specs_select on event_specs for select to authenticated using (
  ((select app.is_admin()) or deleted_at is null)
  and ((select app.is_admin())
       or ((select app.has('events.specs_view'))
           and exists (select 1 from events e where e.id = event_specs.event_id))));

-- ===== 5. אותו שער, על הקבצים =============================================
--
-- הפונקציה נשארת מה שהייתה — היא קוראת את מזהה האירוע מהנתיב ושואלת עליו —
-- ומה שיורד ממנה הוא שורת סוג המשתמש. במקומה, כל צד נשען על המפתח שלו בלבד:
-- קריאה על `events.specs_view` (שסעיף 1 פתח), כתיבה על `events.specs_manage`
-- (שסעיף 3 סגר למשתמשי פורטל). כך אין יותר שני מקומות שמכריעים על סוג
-- המשתמש — יש מרשם הרשאות אחד, והפונקציה רק שואלת אותו.
--
-- security invoker במכוון, כמו ב-0077: ה-exists על events רץ תחת ה-RLS של
-- הקורא, ולכן ההרשאה על הקובץ ממשיכה להיות בדיוק ההרשאה על האירוע.
create or replace function app.may_touch_event_spec(p_name text, p_write boolean)
returns boolean language plpgsql stable set search_path = public as $$
declare v_event uuid;
begin
  -- הנתיב הוא החוזה. כל דבר שאינו '<uuid>/...' בדלי הזה אינו שלנו, ואינו נפתח.
  begin
    v_event := split_part(p_name, '/', 1)::uuid;
  exception when others then
    return false;
  end;

  if not app.is_admin() then
    if p_write and not app.has('events.specs_manage') then return false; end if;
    if not p_write and not app.has('events.specs_view') then return false; end if;
  end if;

  return exists (select 1 from events e where e.id = v_event);
end $$;

comment on function app.may_touch_event_spec(text, boolean) is
  'השער היחיד לדלי event-specs. קריאה נשענת על events.specs_view וכתיבה על '
  'events.specs_manage; סוג המשתמש נשאל במרשם ההרשאות ולא כאן (0102).';
