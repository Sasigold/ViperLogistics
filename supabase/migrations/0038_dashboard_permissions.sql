-- 0038: הרשאות הדשבורד המתכוונן
--
-- הדשבורד הופך מרשימה קבועה של סקשנים לקטלוג ווידג׳טים שהמשתמש מסדר בעצמו,
-- ובעקבות זה נדרשים חמישה מפתחות חדשים. ארבעה מהם נגזרים ממפתח גס שכבר קיים,
-- ולכן איש אינו מאבד — או מקבל — יכולת ברגע שהמיגרציה נוחתת: מי שכבר רואה שכר
-- יראה עלות שכר, ומי שכבר מחזיק `dashboard.financial` יראה עלות קבלנים.
--
-- הקובץ הזה הוא נתונים בלבד: אין בו שינוי מבנה, אין בו שינוי התנהגות, ואין בו
-- הענקה לאף תפקיד. הוא נשלח לפני הכל כדי שהמסכים שיבואו אחריו יוכלו לשאול על
-- המפתחות שלהם.

-- ── סידור אישי ─────────────────────────────────────────────────────────────
-- ברירת המחדל היא "מותר": לסדר את הדשבורד של עצמך אינו נתון שנחשף אלא העדפת
-- תצוגה, וכל מה שהיא נוגעת בו הוא שורה ב-dashboard_layouts שהיא שלך. מי שאין
-- לו `dashboard.view` אינו מגיע למסך מלכתחילה — `RouteGate` חוסם אותו — ולכן
-- אין צורך לכפול כאן את החסימה.
select app.register_permission(
  'dashboard.customize', 'dashboard', 'התאמת דשבורד אישית',
  'בחירת ווידג׳טים, גודלם וסדרם, ושמירת התצוגה',
  'action', true, false,
  array['staff', 'customer_user']::user_kind[], 'dashboard.view', 50);

-- ── עלות קבלנים ────────────────────────────────────────────────────────────
-- `dashboard.financial` כבר שולט על `dashboard_stats.financial` (המחויב מול
-- ששולם לקבלנים). המפתח החדש הוא הפרוסה הדקה שלו, כדי שהווידג׳טים החדשים —
-- יתרה, התיישנות, פילוח לפי קבלן — יישאלו על מפתח משלהם ולא יירשו בטעות כל
-- הרחבה עתידית של המפתח הגס.
select app.register_permission(
  'dashboard.contractor_cost', 'dashboard', 'עלות קבלנים בדשבורד',
  'סכומים מחויבים, ששולמו ויתרה לתשלום — בכרטיסים ובגרפים',
  'field', false, true,
  array['staff']::user_kind[], 'dashboard.financial', 60);

-- ── עלות שכר ───────────────────────────────────────────────────────────────
-- נגזר מ-`attendance.view_pay` ולא מ-`dashboard.financial`: מי שרשאי לראות
-- כמה עולה שעת עבודה הוא מי שכבר רואה שכר בדוח הנוכחות, לא מי שרואה תמחור.
select app.register_permission(
  'dashboard.payroll', 'dashboard', 'עלות שכר בדשבורד',
  'סך העלות, שעות נוספות ובונוסים — מחושב מהנוכחות המאושרת בלבד',
  'field', false, true,
  array['staff']::user_kind[], 'attendance.view_pay', 70);

-- ── רווח גולמי ─────────────────────────────────────────────────────────────
-- היחיד בלי `implied_by`, במכוון. רווח הוא חיסור, ולכן מי שרואה אותו יכול
-- לגזור ממנו את הרכיבים — אין טעם להעמיד פנים שאפשר להראות רווח בלי להראות
-- עלות. הסקשן בשרת ידרוש את ארבעת המפתחות יחד דרך `app.has_all`, וכאן הוא
-- נשאר מפתח שצריך להעניק במפורש ולא כזה שנגרר אחרי מפתח אחר.
select app.register_permission(
  'dashboard.margin', 'dashboard', 'רווח גולמי',
  'הכנסות פחות עלות קבלנים ועלות שכר. אינו כולל תקורה — אין במערכת מודול הוצאות',
  'field', false, true,
  array['staff']::user_kind[], null, 80);

-- ── ברירת המחדל הארגונית ───────────────────────────────────────────────────
select app.register_permission(
  'dashboard.manage_default', 'dashboard', 'ניהול דשבורד ברירת מחדל',
  'קביעת הפריסה שמשתמש חדש רואה, כולל פריסה נפרדת לסוג משתמש',
  'action', false, false,
  array['staff']::user_kind[], 'settings.edit', 90);
