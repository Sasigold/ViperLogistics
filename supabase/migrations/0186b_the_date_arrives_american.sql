-- 0186: התאריך מארקו מגיע אמריקאי
--
-- ‏0183 קראה את `DD/MM/YYYY`, וזו הייתה טעות. מה שהצינור מעביר בפועל הוא
-- ‏**`MM/DD/YYYY HH:mm`**, והראיה חד-משמעית: הזמנה אמיתית נשאה
-- ‏`"09/28/2026 00:00"` — ואין חודש 28. הזמנה שנייה נשאה אירוע ב-`12/07`,
-- הקמה ב-`12/07 18:00` ופירוק ב-`12/08 02:00`: קריאה אמריקאית נותנת ערב
-- ב-7 בדצמבר ופירוק בשתיים לפנות בוקר למחרת, וקריאה ישראלית נותנת פירוק
-- חודש אחרי האירוע. הראשונה היא אירוע; השנייה היא באג.
--
-- **וטעות כאן אינה נראית לעין.** ‏`12/07/2026` נקרא בשתי הצורות בהצלחה —
-- פעם 7 בדצמבר ופעם 12 ביולי — והמשאית פשוט מגיעה בחודש הלא נכון. לכן
-- הכלל כאן אינו "נסה את זה ואם נכשל נסה את ההוא", אלא הכרעה מפורשת:
--
--   1. **‏`MM/DD` היא ברירת המחדל**, כי זה מה שהצד השני שולח.
--   2. **מה שאינו יכול להיות חודש, אינו חודש.** ‏`28/09/2026` ייקרא
--      ‏`DD/MM` — לא כדי "לנחש נכון", אלא כי זו הקריאה היחידה שקיימת.
--   3. **ISO ממשיך לגבור על שניהם** ואינו נוגע בכלל: מחרוזת שמתחילה
--      ב-`YYYY-MM-DD` אינה דו-משמעית, ומי שנושא אזור זמן עובר דרכו.
--
-- אין כאן מה לגבות: `arco_deliveries` ריקה ואף אירוע לא נפתח עדיין מהצינור
-- הזה, ולכן אין תאריך שנכתב שגוי שצריך לתקן.
--
-- ‏(הקובץ הוחל על המסד ב-20260922093734 בשם `0186_the_date_arrives_american`
-- ולא נכנס למאגר; הוא נוסף כאן כפי שהוא, כדי שפריסה מחדש לא תחזיר את
-- הקריאה הישראלית של 0183.)

create or replace function app.arco_local(p_raw text)
returns timestamp language plpgsql stable set search_path = public as $$
declare
  v  text := btrim(coalesce(p_raw, ''));
  m  text[];
  a  int;
  b  int;
  mm int;
  dd int;
begin
  if v = '' then return null; end if;

  m := regexp_match(v,
    '^([0-9]{1,2})/([0-9]{1,2})/([0-9]{4})(?:[ T]([0-9]{1,2}):([0-9]{2})(?::([0-9]{2}))?)?$');
  if m is not null then
    a := m[1]::int;
    b := m[2]::int;
    if a > 12 and b <= 12 then
      -- ‏`28/09` — הראשון אינו יכול להיות חודש, ולכן הוא היום.
      mm := b; dd := a;
    else
      -- ברירת המחדל, וגם המקרה הדו-משמעי: אמריקאי.
      mm := a; dd := b;
    end if;
    return make_timestamp(m[3]::int, mm, dd,
                          coalesce(m[4], '0')::int, coalesce(m[5], '0')::int,
                          coalesce(m[6], '0')::numeric);
  end if;

  if v ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' then
    if v ~ '([Zz]|[+-][0-9]{2}:?[0-9]{2})$' then
      return (v::timestamptz) at time zone 'Asia/Jerusalem';
    end if;
    return v::timestamp;
  end if;

  return null;
exception when others then
  -- שדה פגום אינו מפיל הזמנה שלמה. הוא פשוט אינו ידוע.
  return null;
end $$;

revoke execute on function app.arco_local(text) from anon, authenticated, public;
