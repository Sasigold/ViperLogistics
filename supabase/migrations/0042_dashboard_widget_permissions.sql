-- 0042: הרשאות בונה הווידג׳טים
--
-- הדשבורד המתכוונן (0038-0041) מוסר קטלוג של ווידג׳טים כתובים ביד. הצעד הבא הוא
-- שהמשתמש יבנה ווידג׳ט בעצמו — יבחר מקור, מדד, פילוח וסוג תצוגה. שני מפתחות
-- חדשים, ושניהם על *פעולה*, לא על נתון: כל מקור, מדד, פילוח ושדה סינון מגודרים
-- בנפרד במנוע, והמנוע הוא `security invoker`, ולכן בניית ווידג׳ט אינה מעניקה
-- גישה לשום דבר שלא הייתה קודם.
--
-- הקובץ הזה הוא נתונים בלבד, ונשלח לפני המסכים — בדיוק כמו 0038.

-- ── בניית ווידג׳ט ──────────────────────────────────────────────────────────
-- **בלי `implied_by` ובלי `default_allowed = true`, ושניהם במכוון.**
--
-- הניסוח המתבקש היה `implied_by => 'dashboard.customize'` — "מי שמתאים דשבורד
-- רשאי לבנות". הוא שגוי, וזה בדיוק הבאג ש-0027 תיקנה: `dashboard.customize`
-- נרשם ב-0038 עם `default_allowed = true`, ו-`app.has` (0010) מטפס בשרשרת
-- ה-`implied_by` עד לשכבה הראשונה שיש לה דעה. הוא **אינו מסתכל על
-- `applies_to`** — 0026 אומרת זאת מפורשות — ולכן מפתח שיורש מ-customize היה
-- מוחזר `true` לכל משתמש במערכת, כולל פורטל הלקוחות והקבלנים.
--
-- `kind_permission_defaults` הוא השכבה הנכונה: היא מדברת *אחרי* המענקים
-- האישיים והתפקידיים ו*לפני* ברירת המחדל של הרישום, ולכן היא נותנת בדיוק
-- "כל אנשי הצוות, אף משתמש פורטל, וניתן לשלילה פר-תפקיד ופר-משתמש".
select app.register_permission(
  'dashboard.build_widget', 'dashboard', 'בניית ווידג׳ט',
  'בניית ווידג׳ט מתוך הממשק — בחירת מקור, מדד, פילוח וסוג תצוגה',
  'action', false, false,
  array['staff']::user_kind[], null, 52);

insert into kind_permission_defaults (user_kind, permission_key, allowed)
values ('staff', 'dashboard.build_widget', true)
on conflict (user_kind, permission_key) do update set allowed = excluded.allowed;

-- ── שיתוף לארגון ───────────────────────────────────────────────────────────
-- שיתוף מפרסם **שאילתה**, לא סידור. זה המעשה היחיד כאן שמסך של אדם אחר תלוי
-- בו, ולכן הוא מסומן מסוכן ואין לו `implied_by` — גם לא מ-`dashboard.manage_default`,
-- כי פרסום פריסה ופרסום שאילתה הם שני מעשים שונים.
--
-- מה שהמפתח הזה **אינו** עושה: הוא אינו מעניק לקורא גישה לנתון. ווידג׳ט משותף
-- מוערך מחדש מול המפתחות של כל קורא בזמן ריצה, ולכן שיתוף של ווידג׳ט רווח
-- גולמי אינו חושף רווח גולמי לאיש — הוא רק מציע אותו למי שכבר רשאי.
select app.register_permission(
  'dashboard.share_widget', 'dashboard', 'שיתוף ווידג׳ט לארגון',
  'הפיכת ווידג׳ט שנבנה לזמין לכל מי שרשאי לראות את הנתונים שבו',
  'action', false, true,
  array['staff']::user_kind[], null, 55);
