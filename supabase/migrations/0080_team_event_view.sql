-- 0080: גם נהג וראש צוות פותחים את האירוע מהלוח
--
-- הדיווח: עובד שטח לוחץ על אירוע בלוח השנה ונכנס לצפייה בו — ומי שמוגדר
-- נהג או ראש צוות לוחץ ולא קורה דבר. מבחינת מי שבשטח שלושת התפקידים הם
-- אותו קהל, והלוח באמת מציג לשלושתם את אותם אירועים (היקף 'own' על
-- events יושב על שלושתם — ‏0011 לעובד ולנהג, ‏0066 §7ג לראש הצוות).
-- מה שנבדל הוא המפתח:
--
--   * "עובד" קיבל את events.view ב-0079 §2א.
--   * "ראש צוות" החזיק אותו מ-0011 — ו-0066 §7ג דחה אותו במפורש.
--   * "נהג" מעולם לא החזיק אותו: close_modules ב-0011 סגר לו את המודול כולו.
--
-- הלוח מסתיר את הלחיצה בלי המפתח (eventClick בודק events.view לפני הניווט),
-- ולכן אצל שניהם היא פשוט לא עושה כלום. ההכרעה של 0079 — "לראות את האירוע"
-- כן, כלי עריכה ומסמכים לא — נכונה לשלושתם, והקובץ הזה רק מחיל אותה על
-- השניים שנשארו מאחור.
--
-- אותה תבנית בדיוק כמו 0079 §2א, ומאותו נימוק: המפתחות שנרשמו *אחרי* 0011
-- (יומן הפעילות, המפרט) אין להם שורת דחייה לתפקידים האלה, ובלי כתיבה מחדש
-- מפורשת הם היו נדלקים עכשיו בהיסק מ-events.view שזה עתה הוענק.
insert into role_permissions (role_id, permission_key, allowed)
select r.id, pr.key, pr.key = 'events.view'
from permission_roles r
cross join permission_registry pr
where r.key in ('driver', 'team_lead') and pr.module = 'events' and pr.is_active
on conflict (role_id, permission_key) do update set allowed = excluded.allowed;

