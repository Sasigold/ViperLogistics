import { describe, expect, it } from 'vitest'
import { holidayOn, holidaysInRange, isHebrewLeapYear } from './hebrewHolidays'

/**
 * לוח שנה עברי הוא אריתמטיקה, ואריתמטיקה אפשר לבדוק מול תאריכים ידועים.
 * העוגנים כאן פרושים על שנים פשוטות ומעוברות, ועל כל אחת מהדחיות — צום
 * שחל בשבת, תענית אסתר, יום השואה ליד שבת ויום העצמאות בשלושת המצבים שבהם
 * הוא זז. שגיאה של יום אחד בחישוב תיפול על אחד מהם.
 */

const dateOf = (name: string, from: string, to: string) =>
  [...holidaysInRange(from, to).values()].filter((h) => h.name === name).map((h) => h.date)

describe('שנים מעוברות', () => {
  it('שבע שנים מתוך מחזור של תשע-עשרה', () => {
    const cycle = Array.from({ length: 19 }, (_, i) => isHebrewLeapYear(5776 + i))
    expect(cycle.filter(Boolean)).toHaveLength(7)
    expect(isHebrewLeapYear(5784)).toBe(true)
    expect(isHebrewLeapYear(5786)).toBe(false)
  })
})

describe('מועדי השנה מול תאריכים ידועים', () => {
  it.each([
    ['ראש השנה', '2023-09-01', '2023-09-30', '2023-09-16'],
    ['ראש השנה', '2024-10-01', '2024-10-31', '2024-10-03'],
    ['ראש השנה', '2025-09-01', '2025-09-30', '2025-09-23'],
    ['ראש השנה', '2026-09-01', '2026-09-30', '2026-09-12'],
    ['יום כיפור', '2025-10-01', '2025-10-31', '2025-10-02'],
    ['יום כיפור', '2026-09-01', '2026-09-30', '2026-09-21'],
    ['סוכות', '2025-10-01', '2025-10-31', '2025-10-07'],
    ['שמחת תורה', '2025-10-01', '2025-10-31', '2025-10-14'],
    ['פסח', '2024-04-01', '2024-04-30', '2024-04-23'],
    ['פסח', '2025-04-01', '2025-04-30', '2025-04-13'],
    ['פסח', '2026-04-01', '2026-04-30', '2026-04-02'],
    ['שבועות', '2025-06-01', '2025-06-30', '2025-06-02'],
    ['שבועות', '2026-05-01', '2026-05-31', '2026-05-22'],
    ['ט״ו בשבט', '2026-01-20', '2026-02-15', '2026-02-02'],
    ['ל״ג בעומר', '2025-05-01', '2025-05-31', '2025-05-16'],
    ['יום ירושלים', '2025-05-01', '2025-06-05', '2025-05-26'],
    // שנה מעוברת: פורים באדר ב׳, כחודש אחרי מקומו בשנה פשוטה
    ['פורים', '2024-03-01', '2024-03-31', '2024-03-24'],
    ['פורים', '2025-03-01', '2025-03-31', '2025-03-14'],
    ['פורים', '2026-03-01', '2026-03-31', '2026-03-03'],
  ])('%s בין %s ל-%s', (name, from, to, want) => {
    expect(dateOf(name, from, to)).toEqual([want])
  })

  it('חנוכה נמשך שמונה ימים רצופים מכ״ה בכסלו', () => {
    const days = dateOf('חנוכה', '2025-11-01', '2026-01-31')
    expect(days).toHaveLength(8)
    expect(days[0]).toBe('2025-12-15')
    expect(days[7]).toBe('2025-12-22')
  })
})

describe('דחיות', () => {
  it('תשעה באב שחל בשבת נדחה ליום ראשון', () => {
    // ט׳ באב תשפ״ה חל בשבת 2025-08-02
    expect(dateOf('תשעה באב', '2025-07-20', '2025-08-15')).toEqual(['2025-08-03'])
    expect(dateOf('תשעה באב', '2026-07-01', '2026-07-31')).toEqual(['2026-07-23'])
  })

  it('תענית אסתר שחלה בשבת מוקדמת ליום חמישי', () => {
    expect(dateOf('תענית אסתר', '2025-03-01', '2025-03-31')).toEqual(['2025-03-13'])
    // בשנת תשפ״א י״ג באדר חל בשבת, והצום הוקדם ל-ה׳
    expect(dateOf('תענית אסתר', '2021-02-15', '2021-03-15')).toEqual(['2021-02-25'])
  })

  it('יום השואה אינו נצמד לשבת', () => {
    // כ״ז בניסן תשפ״ה חל בשישי, ולכן היום הוקדם ליום חמישי
    expect(dateOf('יום השואה', '2025-04-01', '2025-04-30')).toEqual(['2025-04-24'])
    expect(dateOf('יום השואה', '2026-04-01', '2026-04-30')).toEqual(['2026-04-14'])
  })

  it('יום העצמאות זז מסוף השבוע ומיום שני', () => {
    // ה׳ באייר תשפ״ד חל בשני — נדחה לשלישי
    expect(dateOf('יום העצמאות', '2024-05-01', '2024-05-31')).toEqual(['2024-05-14'])
    // ה׳ באייר תשפ״ה חל בשבת — הוקדם ליום חמישי
    expect(dateOf('יום העצמאות', '2025-04-25', '2025-05-10')).toEqual(['2025-05-01'])
    // תשפ״ו: ה׳ באייר ברביעי, בלי דחייה
    expect(dateOf('יום העצמאות', '2026-04-01', '2026-04-30')).toEqual(['2026-04-22'])
  })

  it('יום הזיכרון תמיד ביום שלפני יום העצמאות', () => {
    for (const [memorial, independence] of [
      ['2024-05-13', '2024-05-14'],
      ['2025-04-30', '2025-05-01'],
      ['2026-04-21', '2026-04-22'],
    ]) {
      expect(holidayOn(memorial)?.name).toBe('יום הזיכרון')
      expect(holidayOn(independence)?.name).toBe('יום העצמאות')
    }
  })
})

describe('ימים בשבוע שאסורים למועד', () => {
  const weekday = (iso: string) => new Date(`${iso}T00:00:00Z`).getUTCDay()
  const all = [...holidaysInRange('2020-01-01', '2035-12-31').values()]

  it('לא אד״ו ראש — ראש השנה לא חל בראשון, רביעי או שישי', () => {
    const bad = all.filter((h) => h.name === 'ראש השנה' && [0, 3, 5].includes(weekday(h.date)))
    expect(bad).toEqual([])
  })

  it('פורים לעולם לא בשבת, ופסח לא בשני, רביעי או שישי', () => {
    expect(all.filter((h) => h.name === 'פורים' && weekday(h.date) === 6)).toEqual([])
    expect(all.filter((h) => h.name === 'פסח' && [1, 3, 5].includes(weekday(h.date)))).toEqual([])
  })
})

describe('holidaysInRange', () => {
  it('מחזיר רק את מה שבתוך הטווח, כולל קצותיו', () => {
    const map = holidaysInRange('2026-04-02', '2026-04-02')
    expect([...map.keys()]).toEqual(['2026-04-02'])
    expect(map.get('2026-04-02')?.kind).toBe('yomtov')
  })

  it('טווח הפוך או ריק אינו מפיל דבר', () => {
    expect(holidaysInRange('2026-05-01', '2026-04-01').size).toBe(0)
    expect(holidaysInRange('', '').size).toBe(0)
  })

  it('יום רגיל אינו מועד', () => {
    expect(holidayOn('2026-06-10')).toBeUndefined()
  })
})
