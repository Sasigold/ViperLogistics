/**
 * בניית מסנני PostgREST מתוך טקסט שהמשתמש הקליד.
 *
 * ‏`or=(a.ilike.%x%,b.ilike.%x%)` הוא דקדוק, לא מחרוזת: פסיק מפריד בין
 * תנאים, סוגריים תוחמים קבוצה, ונקודה מפרידה בין עמודה לאופרטור לערך.
 * הדבקה של הטקסט הגולמי פנימה נותנת למי שמקליד לכתוב את הדקדוק הזה.
 *
 * בפועל זה לא נראה כמו התקפה אלא כמו חיפוש רגיל. כתובת ישראלית מכילה פסיק
 * כמעט תמיד — "תל אביב, הרצל 5" — והפסיק הזה פיצל את הערך לתנאי נוסף,
 * ‏PostgREST החזיר 400, והמסך הציג הודעת שגיאה על חיפוש תקין לחלוטין.
 *
 * ‏RLS ממשיך לתחום את התוצאות בכל מקרה, ולכן זו נכונות ולא דליפה — אבל
 * הנכונות הזו היא ההבדל בין חיפוש שעובד לבין חיפוש שלא.
 *
 * הפתרון הוא הציטוט ש-PostgREST מגדיר בעצמו: ערך בתוך מרכאות כפולות מכיל
 * תווים שמורים כמות שהם, ובתוכו `"` ו-`\` נמלטים בלוכסן אחורי.
 */

/** ערך יחיד, מצוטט כך ש-PostgREST יקרא אותו כערך ולא כתחביר. */
export function filterValue(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

/**
 * קבוצת `or` של `ilike` על כמה עמודות עם אותו מונח.
 *
 * ‏`%` ו-`_` שהמשתמש הקליד נשארים תווי תבנית של ilike במכוון: זו התנהגות
 * החיפוש שהייתה כאן מאז ומתמיד, והיא שימושית. מה שהשתנה הוא רק שהם — ושאר
 * התווים — כבר אינם יכולים לצאת מהערך אל הדקדוק שמסביבו.
 */
export function ilikeAcross(columns: readonly string[], term: string): string {
  const value = filterValue(`%${term}%`)
  return columns.map((c) => `${c}.ilike.${value}`).join(',')
}
